import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:390,height:844}});
await page.goto('http://127.0.0.1:5173/?mobileVariant=dribbble');await page.locator('.mobile-story[data-scene="0"]').waitFor();
await page.evaluate(()=>scrollBy(0,50));await page.waitForTimeout(200);
await page.locator('button[data-scene="1"]').click();await page.locator('.mobile-story[data-scene="1"]').waitFor();
await page.waitForTimeout(85);
const path=page.locator('.page-indicator-motion path');
const mid=await path.getAttribute('d');const n=mid.match(/[\d.]+/g).map(Number);assert(n[3]-n[1]>.1,mid);
await page.screenshot({path:'test-results/mobile-variants/page-indicator-stretch.png'});
await page.waitForTimeout(260);assert.equal(await path.getAttribute('d'),'M22 66 L22 66.01');
await page.locator('button[data-scene="4"]').click();await page.locator('.mobile-story[data-scene="4"]').waitFor();
await page.locator('button[data-scene="2"]').click();await page.locator('.mobile-story[data-scene="2"]').waitFor();
await page.waitForTimeout(300);assert.equal(await path.getAttribute('d'),'M22 110 L22 110.01');
await page.emulateMedia({reducedMotion:'reduce'});
await page.locator('button[data-scene="3"]').click();await page.locator('.mobile-story[data-scene="3"]').waitFor();
assert.equal(await path.getAttribute('d'),'M22 154 L22 154.01');
await page.waitForTimeout(1000);assert.equal(await page.locator('.mobile-story-progress').evaluate(el=>getComputedStyle(el).opacity),'0');
await browser.close();console.log('PASS: stretch, settle, interrupted/reverse transition, reduced motion, auto-hide');
